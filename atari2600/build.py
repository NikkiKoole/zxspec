#!/usr/bin/env python3
"""Build ATARI JAMS: pick the best-tuned (AUDC, AUDF) for every note the groove
needs (tuning.py), pack the song as per-bar info + 5 drum grooves, build the
playfield meter bytes and the colour gradients, then assemble a 4 KB ROM."""
import math
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from groove import ROOTS, GROOVES, ARRANGEMENT, ARP_SHAPE, ARP_FROM_BAR  # noqa: E402
from tuning import closest, best_key, BASS_LO, CHORDS, BASS_MODES, ARP_MODES  # noqa: E402

T = best_key()
ROOT_ORDER = ["A", "F", "C", "G", "E"]

bass_lo = [closest(BASS_LO[r] + T, BASS_MODES) for r in ROOT_ORDER]
bass_hi = [closest(BASS_LO[r] + 12 + T, BASS_MODES) for r in ROOT_ORDER]
arp = []
for r in ROOT_ORDER:
    root, third = CHORDS[r]
    arp += [closest(m + T, ARP_MODES) for m in (root, root + third, root + 7, root + 12)]

GROOVE_ORDER = ["intro", "verse", "drive", "fill", "end"]
grooves = []
for g in GROOVE_ORDER:
    steps = [0] * 16
    for s, d in GROOVES[g].items():
        steps[s] = d
    grooves += steps
barinfo = [(GROOVE_ORDER.index(ARRANGEMENT[b]) << 4) | ROOT_ORDER.index(ROOTS[b]) for b in range(len(ROOTS))]
barinfo.append(0xFF)                         # one silent bar before it loops

BASS_ENV = [12, 11, 10, 9, 8, 8, 7, 6, 6, 5, 4, 3, 2, 1, 1, 0]
ARP_ENV = [7, 7, 6, 6, 5, 5, 4, 4, 4, 3, 3, 2, 2, 1, 1, 0]
DRUMS = {   # per frame (AUDC, AUDF, AUDV): kick = a falling div-31 buzz, snare/hat = white noise
    "kick":  [(6, f, v) for f, v in zip((4, 7, 10, 14, 18, 23, 28, 31), (15, 14, 12, 10, 8, 5, 3, 0))],
    "snare": [(8, f, v) for f, v in zip((5, 6, 7, 8, 8, 9, 9, 9), (14, 11, 9, 7, 5, 3, 2, 0))],
    "hat":   [(8, 0, v) for v in (6, 3, 1, 0, 0, 0, 0, 0)],
}


def pf_bytes(level):
    """Light the `level` playfield pixels nearest the centre (reflected playfield)."""
    lit = [i >= 20 - level for i in range(20)]
    pf0 = sum(1 << (4 + i) for i in range(4) if lit[i])
    pf1 = sum(1 << (7 - i) for i in range(8) if lit[4 + i])
    pf2 = sum(1 << i for i in range(8) if lit[12 + i])
    return pf0, pf1, pf2


pfm = [pf_bytes(level) for level in range(21)]

# the screen: background, bass meter, background, arp meter, background, drum meter, background
SEG_END = [40, 56, 84, 100, 128, 144, 192]
COL_BASS, COL_ARP, COL_DRUM = 0xC8, 0x58, 0x1C          # NTSC green, purple, yellow
# entering segment i sets SEG_COL[i]; it changes at the end of the line before, so a
# meter's colour must last through the (blank) background segment after it
SEG_COL = [COL_BASS, COL_BASS, COL_BASS, COL_ARP, COL_ARP, COL_DRUM, COL_DRUM, COL_DRUM]


def gradient(hot):
    out = []
    for i in range(512):
        a = 2 * math.pi * (i % 256) / 256
        bar = max(0.0, math.sin(3 * a)) ** 6           # three bars rolling down a dark blue
        lum = 6 * bar + (4 if hot else 0)
        hue = 0x8
        out.append((hue << 4) | (min(14, int(round(lum / 2)) * 2)))
    return out


def B(label, data):
    data = list(data)
    lines = [f"{label}:"]
    for i in range(0, len(data), 16):
        lines.append("        .byte " + ", ".join(f"${v & 0xFF:02x}" for v in data[i:i + 16]))
    return "\n".join(lines)


with open(os.path.join(HERE, "gen.inc"), "w") as f:
    f.write(f"""; generated by build.py (transpose {T:+d})
LAST_BAR = {len(ROOTS) - 1}
LOOP_BARS = {len(ROOTS) + 1}
ARP_FROM_BAR = {ARP_FROM_BAR}

.segment "RODATA"
""")
    f.write("\n".join([
        B("barinfo", barinfo), B("grooves", grooves), B("arp_shape", ARP_SHAPE),
        B("bass_lo_c", [c for c, _, _ in bass_lo]), B("bass_lo_f", [f_ for _, f_, _ in bass_lo]),
        B("bass_hi_c", [c for c, _, _ in bass_hi]), B("bass_hi_f", [f_ for _, f_, _ in bass_hi]),
        B("arp_c", [c for c, _, _ in arp]), B("arp_f", [f_ for _, f_, _ in arp]),
        B("bass_env_tab", BASS_ENV), B("arp_env_tab", ARP_ENV),
        B("drum_c", [c for d in DRUMS.values() for c, _, _ in d]),
        B("drum_f", [f_ for d in DRUMS.values() for _, f_, _ in d]),
        B("drum_v", [v for d in DRUMS.values() for _, _, v in d]),
        B("segend", SEG_END), B("segcol", SEG_COL),
        B("pfm0", [p[0] for p in pfm]), B("pfm1", [p[1] for p in pfm]), B("pfm2", [p[2] for p in pfm]),
        '.segment "GRAD"',
        B("gradtab", gradient(False)), B("gradtab_hot", gradient(True)),
    ]) + "\n")

with open(os.path.join(HERE, "atari.cfg"), "w") as f:
    f.write("""MEMORY {
    ZP:  start = $80, size = $80, type = rw;
    ROM: start = $F000, size = $1000, fill = yes, fillval = $00;
}
SEGMENTS {
    ZEROPAGE: load = ZP,  type = zp;
    CODE:     load = ROM, type = ro, start = $F000;
    RODATA:   load = ROM, type = ro;
    GRAD:     load = ROM, type = ro, start = $F800;
    VECTORS:  load = ROM, type = ro, start = $FFFA;
}
""")

run = lambda *cmd: subprocess.run(cmd, cwd=HERE, check=True)  # noqa: E731
run("ca65", "-o", "main.o", "main.s")
run("ld65", "-C", "atari.cfg", "-o", "atarijams.bin", "-m", "atarijams.map", "main.o")
size = os.path.getsize(os.path.join(HERE, "atarijams.bin"))
used = [l for l in open(os.path.join(HERE, "atarijams.map")) if l.startswith(("CODE", "RODATA"))]
print(f"atarijams.bin: {size} bytes, transpose {T:+d}")
print("".join(used).rstrip())
