#!/usr/bin/env python3
"""Build PC SPEAKER JAMS: song rows tagged with which trick plays each bar, PIT
divisors and oscillator steps, waveforms, drum samples at the PWM rate, the kick's
pitch sweep, and the screen text; then assemble pcjams.com with nasm."""
import math
import os
import random
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from groove import ticks, ROOTS  # noqa: E402

PIT = 1193182
RATE = PIT / 64                  # 18643 Hz: the PWM sample rate (and IRQ0 rate)
random.seed(2026)


def hz(m):
    return 440 * 2 ** ((m - 69) / 12)


# ---------------------------------------------------------------- song
VOICINGS = {"A": (57, 60, 64), "F": (53, 57, 60), "C": (55, 60, 64),
            "G": (55, 59, 62), "E": (56, 59, 64)}
chord_names = list(VOICINGS)
rows = ticks()
for bar in range(len(rows) // 16):
    engine = 0 if bar < 8 else 1 if bar < 16 else 2      # trick 1 / 2 / 3
    for i in range(16):
        pad = 0
        if bar < len(ROOTS):
            if bar >= 16 and i == 0:
                pad = 2 + chord_names.index(ROOTS[bar])
            if bar == len(ROOTS) - 1 and i == 14:
                pad = 1
        rows[bar * 16 + i] += [engine, pad]
song = [v for r in rows for v in r]

divtab = [max(1, min(65535, round(PIT / hz(m)))) for m in range(128)]
inctab = [min(65535, round(hz(m) / RATE * 65536)) for m in range(128)]

# ---------------------------------------------------------------- waves + drums
sine = [round(120 * math.tanh(1.2 * (math.sin(2 * math.pi * i / 256) + 0.25 * math.sin(4 * math.pi * i / 256))))
        for i in range(256)]
tri = [round(120 * (1 - 4 * abs(i / 256 - 0.5))) for i in range(256)]
saw_raw = [sum(math.sin(2 * math.pi * h * i / 256) / h for h in range(1, 9)) for i in range(256)]
saw = [round(v / max(abs(s) for s in saw_raw) * 110) for v in saw_raw]


def s8(xs):
    pk = max(abs(x) for x in xs) or 1
    return [round(x / pk * 120) for x in xs]


def kick(secs=0.18):
    out, ph = [], 0.0
    for i in range(int(secs * RATE)):
        t = i / RATE
        ph += 2 * math.pi * (50 + 150 * math.exp(-t / 0.03)) / RATE
        out.append(math.tanh(1.5 * math.sin(ph) * math.exp(-t / 0.08)))
    return s8(out)


def snare(secs=0.16):
    out = []
    for i in range(int(secs * RATE)):
        t = i / RATE
        body = math.sin(2 * math.pi * 190 * t) * math.exp(-t / 0.03) * 0.5
        out.append(body + random.uniform(-1, 1) * math.exp(-t / 0.05) * 0.8)
    return s8(out)


def hat(secs=0.04):
    out, prev = [], 0.0
    for i in range(int(secs * RATE)):
        n = random.uniform(-1, 1)
        out.append((n - prev) * math.exp(-i / RATE / 0.01) * 0.5)
        prev = n
    return s8(out)


drums = [kick(), snare(), hat()]
DRUM_UPDATES = 40                # tricks 1/2: a drum hit lasts 40 updates (~40 ms)
kick_sweep = [round(PIT / (60 + 340 * math.exp(-(DRUM_UPDATES - k) / 8))) for k in range(DRUM_UPDATES)]

# ---------------------------------------------------------------- screen text
WHITE, YELLOW, CYAN, GREY, GREEN = 0x0F, 0x0E, 0x0B, 0x07, 0x0A


def line(row, col, attr, text):
    return [row, col, attr] + [ord(c) for c in text] + [0]


static = (line(1, 30, YELLOW, "PC SPEAKER JAMS")
          + line(2, 21, GREY, "one pin, on or off, and a timer chip")
          + line(7, 4, 0x0A, "BASS") + line(8, 4, 0x0D, "ARP") + line(9, 4, 0x06, "PADS")
          + line(10, 4, 0x0E, "DRUMS")
          + line(13, 4, GREY, "the speaker:")
          + line(22, 4, GREY, "GROOVE BY CLAUDE, 2026        ESC quits")
          + [0xFF])
TRICKS = [
    ("TRICK 1  ONE SQUARE WAVE", "the timer plays the bass; drums cut in: a falling sweep, random pitches"),
    ("TRICK 2  FAKE POLYPHONY", "the speaker hops between bass and arpeggio 25 times a second"),
    ("TRICK 3  REALSOUND PWM", "18643 pulses a second; their widths ARE the samples: a full software mix"),
]
trick_text = []
for title, desc in TRICKS:
    trick_text.append(line(4, 4, CYAN, title.ljust(74)) + line(5, 4, WHITE, desc.ljust(74)) + [0xFF])

# ---------------------------------------------------------------- emit
def db(label, data, per=24):
    data = list(data)
    out = [f"{label}:"]
    for i in range(0, len(data), per):
        out.append("        db " + ", ".join(str(v & 0xFF if v < 0 else v) for v in data[i:i + per]))
    return "\n".join(out)


def dw(label, data, per=16):
    out = [f"{label}:"]
    for i in range(0, len(data), per):
        out.append("        dw " + ", ".join(str(v) for v in data[i:i + per]))
    return "\n".join(out)


with open(os.path.join(HERE, "gen_equ.asm"), "w") as f:
    f.write(f"""; generated by build.py
ROW_BYTES equ 5
DRUM_UPDATES equ {DRUM_UPDATES}
METER_ROW equ 7
METER_COL equ 12
CONE_ROW equ 15
CONE_COL equ 6
""")
with open(os.path.join(HERE, "gen_data.asm"), "w") as f:
    f.write("\n".join([
        "; generated by build.py - do not edit",
        db("song", song, 30) + "\nsong_end:",
        dw("divtab", divtab), dw("inctab", inctab),
        db("chordtab", [n for c in chord_names for n in VOICINGS[c]]),
        db("sine", sine, 32), db("tri", tri, 32), db("saw", saw, 32),
        dw("kick_sweep", kick_sweep),
        db("kick_pcm", drums[0], 32), db("snare_pcm", drums[1], 32), db("hat_pcm", drums[2], 32),
        "smp_start: dw kick_pcm, snare_pcm, hat_pcm",
        "smp_len:   dw " + ", ".join(str(len(d)) for d in drums),
        db("static_text", static, 32),
        db("trick0", trick_text[0], 32), db("trick1", trick_text[1], 32), db("trick2", trick_text[2], 32),
        "trick_text: dw trick0, trick1, trick2",
    ]) + "\n")

subprocess.run(["nasm", "-f", "bin", "-o", "pcjams.com", "main.asm"], cwd=HERE, check=True)
size = os.path.getsize(os.path.join(HERE, "pcjams.com"))
print(f"pcjams.com: {size} bytes")
assert size < 60000
