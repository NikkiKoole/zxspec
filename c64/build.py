#!/usr/bin/env python3
"""Generate song.asm (song rows, frequency table, screen, raster colours) and
assemble c64jams.prg with ACME. Same groove as Speccy Jams 2: octave-bouncing
bass, a soft arpeggio from bar 9, and kick/snare/hi-hat."""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PAL_CLOCK = 985248

sys.path.insert(0, os.path.dirname(HERE))
from groove import ticks as groove_ticks  # noqa: E402

ticks = groove_ticks()

# ---------------------------------------------------------------- tables
def freq(m):
    hz = 440 * 2 ** ((m - 69) / 12)
    return min(65535, round(hz * 16777216 / PAL_CLOCK))


freqs = [freq(m) for m in range(128)]

BAR_PATTERN = [0, 0, 6, 6, 14, 14, 3, 3, 1, 1, 3, 3, 14, 14, 6, 6,
               0, 0, 9, 9, 2, 2, 8, 8, 7, 7, 8, 8, 2, 2, 9, 9]
bartab = (BAR_PATTERN * 8)[:256]


def scr(text):
    out = []
    for ch in text.lower():
        if "a" <= ch <= "z":
            out.append(ord(ch) - 96)
        elif 32 <= ord(ch) <= 63:
            out.append(ord(ch))
        else:
            out.append(32)
    return out


screen = [32] * 1024
colours = [1] * 1024


def put(row, col, text, colour):
    for i, c in enumerate(scr(text)):
        screen[row * 40 + col + i] = c
        colours[row * 40 + col + i] = colour


put(3, 15, "c64 jams", 7)
put(5, 6, "bass + arp + drums on the sid", 3)
put(12, 4, "bass", 13)
put(14, 4, "arp", 13)
put(16, 4, "drums", 13)
for row, colour in ((12, 5), (14, 4), (16, 7)):         # meter colours
    for col in range(12, 32):
        colours[row * 40 + col] = colour
put(21, 9, "groove by claude, 2026", 10)
screen[1000:] = [0] * 24                                # sprite pointers


def byte_lines(label, data, per=16):
    lines = [f"{label}:"] if label else []
    for i in range(0, len(data), per):
        lines.append("        !byte " + ", ".join(f"${b:02x}" for b in data[i:i + per]))
    return "\n".join(lines)


song_bytes = [b for row in ticks for b in row]
asm = "\n\n".join([
    "; generated by build.py - do not edit",
    byte_lines("song", song_bytes, 24) + "\nsong_end:",
    byte_lines("freqlo", [f & 0xFF for f in freqs]),
    byte_lines("freqhi", [f >> 8 for f in freqs]),
    byte_lines("bartab", bartab),
    byte_lines("screen", screen, 40),
    byte_lines("colours", colours, 40),
]) + "\n"
open(os.path.join(HERE, "song.asm"), "w").write(asm)

subprocess.run(["acme", "-v1", "main.asm"], cwd=HERE, check=True)
size = os.path.getsize(os.path.join(HERE, "c64jams.prg"))
print(f"c64jams.prg: {size} bytes, {len(ticks)} sixteenths "
      f"({len(ticks) * 6 / 50:.1f}s per loop)")
